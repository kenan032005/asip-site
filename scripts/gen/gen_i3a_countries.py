def body_chars(sections):
    """count chinese chars in section bodies (exclude lead)"""
    total = 0
    for k, v in sections.items():
        if k == "lead":
            continue
        if isinstance(v, str):
            total += len(v)
        elif isinstance(v, list):
            total += sum(len(str(x)) for x in v)
        elif isinstance(v, dict):
            if v.get("p"):
                total += sum(len(str(x)) for x in v["p"])
            if v.get("list"):
                total += sum(len(str(x)) for x in v["list"])
            if v.get("table"):
                for row in v["table"].get("rows", []):
                    total += sum(len(str(x)) for x in row)
    return total

